#!/usr/bin/env bash
# =============================================================================
# MxTac — Zero-Downtime Update
# Usage: sudo bash update.sh
# =============================================================================
set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; BOLD='\033[1m'; NC='\033[0m'
log() { echo -e "${GREEN}[update]${NC} $*"; }
err() { echo -e "${RED}[ERR]${NC} $*" >&2; }

DEPLOY_DIR="/opt/mxtac"
REPO_DIR="$(cd "$(dirname "$0")" && pwd)"

[[ $EUID -ne 0 ]] && { err "Run as root: sudo bash update.sh"; exit 1; }

cd "${DEPLOY_DIR}"

log "Syncing updated source files..."
# docker-compose.yml and nginx/ in the deploy directory were generated by
# setup.sh. The files of the same name in the repository belong to other
# setups and must not replace them.
rsync -a --exclude='.venv' --exclude='node_modules' --exclude='__pycache__' \
  --exclude='.git' --exclude='*.pyc' --exclude='.env' \
  --exclude='/docker-compose.yml' --exclude='/nginx/' \
  "${REPO_DIR}/" "${DEPLOY_DIR}/"

log "Rebuilding images..."
docker compose build --quiet

log "Running migrations with the new backend image..."
docker compose run --rm --no-deps -T backend alembic upgrade head

log "Rolling update — backend..."
docker compose up -d --no-deps backend

log "Rolling update — frontend..."
docker compose up -d --no-deps frontend

log "Reloading Nginx..."
docker compose exec -T nginx nginx -s reload

log "Update complete."
docker compose ps
